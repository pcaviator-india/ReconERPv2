window.translations = translations;

/*
 * Ensure a single global `t` helper exists to avoid duplicate declarations
 * in modules that also declare `const t = ...` or `function t(...)`.
 */
if (typeof window.t === 'undefined') {
  window.t = function (k) {
    return typeof getI18nText === 'function' ? getI18nText(k) : (translations && translations.en && translations.en[k]) || k;
  };
}

var currentLang = window.currentLang || localStorage.getItem('recon_lang') || 'es';
window.currentLang = currentLang;

/*
 * Usage: getI18nText('btn_save') => "Save" or "Guardar"
 */
function i18n(key, fallback) { 
  if (!translations[currentLang]) return fallback || key;
  return translations[currentLang][key] || fallback || key; 
}

function toggleLanguage() {
  currentLang = (currentLang === 'es') ? 'en' : 'es';
  localStorage.setItem('recon_lang', currentLang);
  updateUI();
}

/**
 * FIXED: This now looks for a <span> inside the element with the data-i18n attribute.
 * This prevents the translation from deleting your <i> icon tags.
 */
function updateUI() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = i18n(key);
    
    // TARGET ONLY THE SPAN: This protects your <i> icons!
    const labelSpan = el.querySelector('.i18n-label');
    if (labelSpan) {
      labelSpan.innerText = translation;
    } else {
      el.innerText = translation;
    }
  });
  
  // Update all data-i18n-placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = i18n(key);
  });
}

/**
 * Helper function to get translated text from JS
 * Usage: getI18nText('btn_save') => "Save" or "Guardar"
 */
function getI18nText(key) {
  return i18n(key);
}

/**
 * Helper to translate element text dynamically
 * Usage: updateElementText('element_id', 'key')
 */
function updateElementText(elementId, key) {
  const el = document.getElementById(elementId);
  if (el) {
    el.innerText = i18n(key);
  }
}

/**
 * Helper to set placeholder for input/select elements
 * Usage: setElementPlaceholder('search_field', 'search_label')
 */
function setElementPlaceholder(elementId, key) {
  const el = document.getElementById(elementId);
  if (el) {
    el.placeholder = i18n(key);
  }
}

/**
 * Helper to update select/dropdown options with translations
 * Usage: updateSelectOptions('filter_id', array, 'all_categories')
 */
function updateSelectOptions(elementId, options, newOptionKey) {
  const el = document.getElementById(elementId);
  if (!el) return;
  
  const newOptionText = i18n(newOptionKey);
  el.innerHTML = `<option value="">${newOptionText}</option>`;
  
  if (Array.isArray(options)) {
    options.forEach(opt => {
      const optionEl = document.createElement('option');
      optionEl.value = opt;
      optionEl.textContent = opt;
      el.appendChild(optionEl);
    });
  }
}
